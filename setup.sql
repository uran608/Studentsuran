-- Run this in Supabase Dashboard > SQL Editor.
create table if not exists public.sessions (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 120),
  session_date date not null,
  location text not null check (char_length(location) between 1 and 120),
  description text not null check (char_length(description) between 1 and 4000),
  image_url text,
  published boolean not null default false,
  author_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
alter table public.sessions enable row level security;
drop policy if exists "Public can read published sessions" on public.sessions;
create policy "Public can read published sessions" on public.sessions for select to anon, authenticated using (published = true or auth.uid() = author_id);
drop policy if exists "Admin can add own sessions" on public.sessions;
create policy "Admin can add own sessions" on public.sessions for insert to authenticated with check (auth.uid() = author_id);
drop policy if exists "Admin can edit own sessions" on public.sessions;
create policy "Admin can edit own sessions" on public.sessions for update to authenticated using (auth.uid() = author_id) with check (auth.uid() = author_id);
drop policy if exists "Admin can delete own sessions" on public.sessions;
create policy "Admin can delete own sessions" on public.sessions for delete to authenticated using (auth.uid() = author_id);

-- Create a PUBLIC bucket so published images can be viewed without login.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('session-photos', 'session-photos', true, 5242880, array['image/jpeg','image/png','image/webp'])
on conflict (id) do update set public = true, file_size_limit = 5242880, allowed_mime_types = array['image/jpeg','image/png','image/webp'];
drop policy if exists "Public can view session photos" on storage.objects;
create policy "Public can view session photos" on storage.objects for select to public using (bucket_id = 'session-photos');
drop policy if exists "Admin can upload own session photos" on storage.objects;
create policy "Admin can upload own session photos" on storage.objects for insert to authenticated with check (bucket_id = 'session-photos' and (storage.foldername(name))[1] = auth.uid()::text);
